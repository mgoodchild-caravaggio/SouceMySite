// Writes supabase/seed.sql from the fictional sample contacts in src/data/seed.ts.
// Run from the project root with: npm run seed:generate
import { writeFileSync } from 'node:fs';
import { SEED_CONTACTS } from '../src/data/seed';

const str = (v: string | undefined | null) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const num = (v: number | undefined) => (v == null ? 'null' : String(v));
const arr = (v: string[]) => (v.length ? `array[${v.map(str).join(', ')}]` : `'{}'::text[]`);

const contactRows = SEED_CONTACTS.map((c) =>
  `  (${[
    str(c.id), str(c.business), String(c.isProspect), str(c.firstName), str(c.lastName), str(c.company), str(c.title),
    str(c.phone), str(c.phone2), str(c.email), str(c.website), str(c.mailingAddress), str(c.status), str(c.leadSource),
    arr(c.regions), arr(c.categories), arr(c.customerTypes), num(c.dealValue), str(c.followUpOn), arr(c.campaigns), str(c.notes),
  ].join(', ')})`,
);

const propertyRows = SEED_CONTACTS.flatMap((c) =>
  c.properties.map((pr) =>
    `  (${[str(`${c.id}-${pr.id}`), str(c.id), str(pr.address), num(pr.lat), num(pr.lng), num(pr.acres), str(pr.category), str(pr.relation)].join(', ')})`,
  ),
);

const sql = `-- Generated by scripts/generate-seed.ts. Fictional sample data: 555-01xx/02xx phones, @example.com emails.
insert into public.contacts
  (id, business, is_prospect, first_name, last_name, company, title, phone, phone_2, email, website, mailing_address,
   status, lead_source, regions, categories, customer_types, deal_value, follow_up_on, campaigns, notes)
values
${contactRows.join(',\n')}
on conflict (id) do nothing;

insert into public.properties (id, contact_id, address, lat, lng, acres, category, relation)
values
${propertyRows.join(',\n')}
on conflict (id) do nothing;

-- Loading sample data isn't team activity, so drop the automatic "created" entries it produced.
delete from public.activities where kind = 'created' and created_by is null;
`;

writeFileSync('supabase/seed.sql', sql);
console.log(`Wrote ${contactRows.length} contacts and ${propertyRows.length} properties to supabase/seed.sql`);
