// Writes supabase/seed.sql from the fictional sample prospects in src/data/seed.ts.
// Run from the project root with: npm run seed:generate
import { writeFileSync } from 'node:fs';
import { SEED_PROSPECTS } from '../src/data/seed';

const str = (v: string | undefined | null) => (v == null ? 'null' : `'${v.replace(/'/g, "''")}'`);
const num = (v: number | undefined) => (v == null ? 'null' : String(v));
const arr = (v: string[]) => (v.length ? `array[${v.map(str).join(', ')}]` : `'{}'::text[]`);

const prospectRows = SEED_PROSPECTS.map((p) =>
  `  (${[
    str(p.id), str(p.firstName), str(p.lastName), str(p.company), str(p.phone), str(p.email),
    str(p.status), str(p.leadSource), arr(p.regions), arr(p.categories), arr(p.customerTypes),
    num(p.dealValue), String(p.followUp), arr(p.campaigns), str(p.notes),
  ].join(', ')})`,
);

const propertyRows = SEED_PROSPECTS.flatMap((p) =>
  p.properties.map((pr) =>
    `  (${[str(`${p.id}-${pr.id}`), str(p.id), str(pr.address), num(pr.lat), num(pr.lng), num(pr.acres), str(pr.category), str(pr.relation)].join(', ')})`,
  ),
);

const sql = `-- Generated by scripts/generate-seed.ts. Fictional sample data: 555-01xx phones, @example.com emails.
insert into public.prospects
  (id, first_name, last_name, company, phone, email, status, lead_source, regions, categories, customer_types, deal_value, follow_up, campaigns, notes)
values
${prospectRows.join(',\n')}
on conflict (id) do nothing;

insert into public.properties (id, prospect_id, address, lat, lng, acres, category, relation)
values
${propertyRows.join(',\n')}
on conflict (id) do nothing;
`;

writeFileSync('supabase/seed.sql', sql);
console.log(`Wrote ${prospectRows.length} prospects and ${propertyRows.length} properties to supabase/seed.sql`);
